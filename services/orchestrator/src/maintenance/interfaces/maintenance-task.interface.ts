/**
 * Maintenance Task Interface
 *
 * Core interfaces for the Maintenance Task Framework.
 * All maintenance tasks implement IMaintenanceTask and return TaskResult.
 */

/**
 * Task metadata - describes the task's configuration and schedule
 */
export interface TaskMetadata {
  /** Unique identifier for the task (used in API calls and configuration) */
  name: string;

  /** Human-readable description of what the task does */
  description: string;

  /** Cron expression for scheduling (e.g., every 5 minutes, hourly, daily) */
  schedule: string;

  /** Priority (higher = runs first when multiple tasks scheduled at same time) */
  priority: number;

  /** Task category for organization and bulk operations */
  category: 'health-check' | 'cleanup' | 'recovery' | 'metrics' | 'custom';

  /** Timeout in milliseconds (task will be killed if exceeds this) */
  timeoutMs: number;

  /** Whether this task is enabled (can be toggled via env vars) */
  enabled: boolean;

  /** Optional: Dependencies on other tasks (must complete successfully first) */
  dependencies?: string[];

  /**
   * Optional: Postgres advisory-lock ID (LEADER-1) — when set, `BaseMaintenanceTask.execute()`
   * wraps the run in `AdvisoryLockService.runExclusive(lockId, ...)` so only one execution
   * (scheduled OR manually-triggered) runs at a time across all replicas/concurrent callers.
   * Omit only for tasks that intentionally have no leader-election requirement.
   */
  lockId?: number;
}

/**
 * Task execution result - returned by all task executions
 */
export interface TaskResult {
  /** Whether the task completed successfully */
  success: boolean;

  /** Summary message describing the execution */
  message: string;

  /** Detailed findings (issues detected, anomalies, etc.) */
  findings?: TaskFinding[];

  /** Actions taken by the task (auto-fixes, alerts, etc.) */
  actions?: TaskAction[];

  /** Metrics generated by this run (for monitoring dashboards) */
  metrics?: Record<string, number>;

  /** Execution time in milliseconds */
  executionTimeMs?: number;

  /** Any error that occurred (stack trace, etc.) */
  error?: string;
}

/**
 * A finding discovered by the task
 */
export interface TaskFinding {
  /** Severity of the finding */
  severity: 'info' | 'warning' | 'error' | 'critical';

  /** Description of what was found */
  description: string;

  /** Related subject (job ID, step ID, etc.) */
  subjectId?: string;

  /** Subject type for context */
  subjectType?: 'job' | 'step' | 'system';

  /** Additional context data */
  context?: Record<string, any>;
}

/**
 * An action taken by the task
 */
export interface TaskAction {
  /** Type of action taken */
  type: 'auto-fix' | 'alert' | 'metric' | 'manual-review-required';

  /** Description of the action */
  description: string;

  /** Subject affected by the action (job ID, step ID, etc.) */
  subjectId?: string;

  /** Result of the action */
  result?: 'success' | 'failed' | 'skipped';

  /** Additional context */
  context?: Record<string, any>;
}

/**
 * Main interface that all maintenance tasks must implement
 */
export interface IMaintenanceTask {
  /** Get task metadata (configuration, schedule, etc.) */
  getMetadata(): TaskMetadata;

  /** Check if task can run (e.g., check prerequisites, feature flags) */
  canRun(): Promise<boolean>;

  /** Execute the task and return results */
  execute(options?: Record<string, any>): Promise<TaskResult>;

  /** Optional: Cleanup after execution (close connections, etc.) */
  cleanup?(): Promise<void>;
}
