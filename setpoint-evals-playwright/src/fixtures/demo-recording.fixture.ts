/**
 * Recording fixture for the Phase 5 subtitled story demos.
 *
 * Deliberately distinct from `dashboard.fixture.ts` (used by multi-job-demo.spec.ts,
 * untouched): those demos trigger workflows straight through the API. The three
 * story demos instead drive the monitor's Scenarios screen (open eval -> read the
 * gherkin+mermaid "contract" -> click Run -> deep-link to Dashboard -> watch the
 * outcome land), so this fixture just needs a recorded Page pointed at the ALREADY
 * RUNNING monitor dev server — it does not self-boot one (see
 * scenarios-dashboard.fixture.ts's header for why that fixture boots its own: this
 * one is for slow, narrated recordings against a stack a human/agent already brought
 * up, not a hermetic per-test SE).
 *
 * DASHBOARD_URL defaults to :5173 (the documented monitor dev port) — NOT
 * hard-defaulted to whatever port happened to be free today (see DEMO-VIDEOS.md).
 * Pass DASHBOARD_URL explicitly when the monitor is on a shifted port.
 *
 * Each test names its own recording via `test.use({ demoSlug: '...' })` so the
 * regeneration script can find `<slug>.webm` by name instead of guessing which
 * autogenerated hash Playwright's video recorder produced.
 *
 * Deliberately OUTSIDE `test-results/`: Playwright wipes its `outputDir`
 * (default `test-results/`) at the START of every `playwright test`
 * invocation — including subdirectories a fixture writes into by hand. Three
 * separate `playwright test -g '<one demo>'` invocations run back-to-back
 * would each silently delete the previous run's renamed webm before it could
 * be converted. `demo-recordings/` sits next to `test-results/`, not inside
 * it, so it survives across separate invocations and only ever gets
 * overwritten by an explicit re-run of that same demo.
 */

import * as fs from 'fs';
import * as path from 'path';
import { chromium, type Page, type Browser } from '@playwright/test';
import { test as dbTest } from './db-client.fixture';

const VIDEO_DIR = path.resolve(__dirname, '../../demo-recordings');

export const test = dbTest.extend<{ dashboardPage: Page; demoSlug: string }>({
  // Fixture "option" — spec files override via test.use({ demoSlug: '...' }).
  // eslint-disable-next-line no-empty-pattern
  demoSlug: ['unnamed-demo', { option: true }],

  dashboardPage: async ({ demoSlug }, use, testInfo) => {
    fs.mkdirSync(VIDEO_DIR, { recursive: true });
    const dashboardUrl = process.env.DASHBOARD_URL ?? 'http://localhost:5173';

    const browser: Browser = await chromium.launch();
    const context = await browser.newContext({
      viewport: { width: 1280, height: 900 },
      recordVideo: { dir: VIDEO_DIR, size: { width: 1280, height: 900 } },
    });
    const page = await context.newPage();

    await page.goto(dashboardUrl, { waitUntil: 'networkidle', timeout: 15_000 });
    await page.waitForSelector('.header', { timeout: 10_000 });

    await use(page);

    // Teardown: close context to flush the video to disk, then rename the
    // autogenerated hash filename to the demo's own slug so the ffmpeg
    // post-production step (DEMO-VIDEOS.md) can find it deterministically.
    const video = page.video();
    await context.close();
    await browser.close();

    if (video) {
      const generatedPath = await video.path();
      const dest = path.join(VIDEO_DIR, `${demoSlug}.webm`);
      fs.renameSync(generatedPath, dest);
      await testInfo.attach('demo-video', { path: dest, contentType: 'video/webm' });
    }
  },
});

export { expect } from '@playwright/test';
